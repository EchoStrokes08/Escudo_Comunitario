# Caja envolvente (bounding box) del polígono con margen de seguridad
BBOX_BOSA = {
    "min_lat": 4.5950,
    "max_lat": 4.6560,
    "min_lng": -74.2245,
    "max_lng": -74.1515,
}


def punto_en_poligono(lat: float, lng: float, vertices=VERTICES_BOSA) -> bool:
    """Algoritmo ray casting (Jordan curve theorem) sobre el perímetro de Bosa."""
    dentro = False
    n = len(vertices)
    j = n - 1
    for i in range(n):
        lat_i, lng_i = vertices[i]
        lat_j, lng_j = vertices[j]
        if (lng_i > lng) != (lng_j > lng):
            cruce = (lat_j - lat_i) * (lng - lng_i) / (lng_j - lng_i) + lat_i
            if lat < cruce:
                dentro = not dentro
        j = i
    return dentro


def dentro_de_bosa(lat, lng) -> bool:
    """True si (lat, lng) está dentro del polígono de Bosa y dentro de la bbox."""
    try:
        lat, lng = float(lat), float(lng)
    except (TypeError, ValueError):
        return False
    if not (BBOX_BOSA["min_lat"] <= lat <= BBOX_BOSA["max_lat"]):
        return False
    if not (BBOX_BOSA["min_lng"] <= lng <= BBOX_BOSA["max_lng"]):
        return False
    return punto_en_poligono(lat, lng)
